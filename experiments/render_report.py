"""Render docs/research/results.md from experiments/results/*.json. Every number comes from the JSON; nothing is typed by hand."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RES = ROOT / "results"


def f(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def main() -> int:
    r = json.loads((RES / "latest.json").read_text())
    cal = json.loads((RES / "calibration.json").read_text()) if (RES / "calibration.json").exists() else None
    env, ds = r["environment"], r["dataset"]
    L = ["# Evaluation results (generated)", "",
         "> Generated by `experiments/render_report.py` from `experiments/results/latest.json`. Do not edit by hand.", ""]
    if env["mock"]:
        L += ["> **MOCK COMPONENTS.** Hashing embedder and/or `MockLLM` produced these numbers. They validate plumbing and compare retrieval "
              "strategies on a controlled synthetic corpus. They are **not** evidence of real-world answer quality.", ""]
    L += ["## Setup", "", f"* Generated: {r['generated_at']}", f"* Dataset: `{ds['name']}` — {ds['n_questions']} questions. {ds['description']}",
          f"* LLM `{env['llm']}`, embedder `{env['embedder']}`, reranker `{env['reranker']}`, repeats {env['repeats']} (median latency), seed {env['seed']}",
          f"* Reported split: **{env['split']}** (thresholds were tuned on **dev** only)", f"* Git commit: {env['git_commit'] or 'not committed yet'}", "",
          "## Retrieval (answerable questions, reported split)", "",
          "| System | nDCG@5 | nDCG@10 [95% CI] | Recall@10 | MRR | P@5 |", "|---|---|---|---|---|---|"]
    for s in r["systems"]:
        x = s["retrieval"]
        L.append(f"| {s['id']} {s['name']} | {f(x['ndcg_at_5'])} | {f(x['ndcg_at_10'])} [{f(x['ndcg_at_10_ci_low'])}, {f(x['ndcg_at_10_ci_high'])}] | "
                 f"{f(x['recall_at_10'])} | {f(x['mrr'])} | {f(x['precision_at_5'])} |")
    L += ["", "## Cost and latency", "", "| System | mean ms | P50 | P95 | LLM calls (mean / median) | failures |", "|---|---|---|---|---|---|"]
    for s in r["systems"]:
        e = s["engineering"]
        L.append(f"| {s['id']} | {f(e['latency_mean_ms'], 1)} | {f(e['latency_p50_ms'], 1)} | {f(e['latency_p95_ms'], 1)} | "
                 f"{f(e['llm_calls_mean'])} / {f(e['llm_calls_median'], 0)} | {f(e['failure_rate'])} |")
    classes = sorted({c for s in r["systems"] for c in s["by_class"]})
    L += ["", "## nDCG@10 by query class", "", "| System | " + " | ".join(classes) + " |", "|---|" + "---|" * len(classes)]
    for s in r["systems"]:
        L.append(f"| {s['id']} | " + " | ".join(f(s["by_class"].get(c, {}).get("ndcg_at_10")) for c in classes) + " |")
    h = r["hypotheses"]
    L += ["", "## Pre-registered hypotheses (docs/research/adaptive-retrieval-protocol.md)", ""]
    if "H1_quality_S5_vs_S4_ndcg10" in h:
        a = h["H1_quality_S5_vs_S4_ndcg10"]
        L.append(f"* **H1 quality (S5 vs S4, nDCG@10):** Δ = {f(a['mean_diff'])} [{f(a['ci_low'])}, {f(a['ci_high'])}], n={a['n']}. "
                 f"Non-inferiority (CI lower bound > −0.02): **{a['non_inferior_margin_0.02']}**.")
        b = h["H2_cost_llm_calls"]
        L.append(f"* **H2 LLM calls:** S5 mean {f(b['S5_mean'])} / median {b['S5_median']} vs S4 mean {f(b['S4_mean'])} / median {b['S4_median']} → supported: **{b['supported']}**.")
        c = h["H3_latency"]
        L.append(f"* **H3 latency:** S5 mean {f(c['S5_mean_ms'], 1)} ms, P95 {f(c['S5_p95_ms'], 1)} vs S4 mean {f(c['S4_mean_ms'], 1)} ms, P95 {f(c['S4_p95_ms'], 1)} → supported: **{c['supported']}**.")
    if "H4_lookup_S5_vs_S2_ndcg10" in h:
        d = h["H4_lookup_S5_vs_S2_ndcg10"]
        L.append(f"* **H4 lookup routing:** S5 − S2 nDCG@10 = {f(d['mean_diff'])} [{f(d['ci_low'])}, {f(d['ci_high'])}], n={d['n']}; matches or beats: **{d['matches_or_beats']}**; "
                 f"cheaper than S3 (latency {f(d['S5_latency_ms'], 1)} vs {f(d['S3_latency_ms'], 1)} ms): **{d['S5_cheaper_than_S3_latency']}**.")
    if "H5_confidence_auroc_vs_recall10_full" in h:
        e = h["H5_confidence_auroc_vs_recall10_full"]
        L.append(f"* **H5 confidence signal (pre-registered label Recall@10=1):** AUROC = {f(e['auroc'])} (n={e['n']}, {e['n_success']} successes). "
                 f"{e['note'] or ''} Supported: **{e['supported']}**.")
        p = h["H5_posthoc_confidence_auroc_vs_gold_at_rank1"]
        L.append(f"  * Post-hoc (not pre-registered), label gold-document-at-rank-1: AUROC = {f(p['auroc'])} (n={p['n']}, {p['n_success']} successes).")
    if "per_class_wilcoxon_S5_vs_S4_ndcg10" in h:
        L += ["", "### Per-class Wilcoxon S5 vs S4 (nDCG@10, Holm-corrected)", "", "| class | n non-zero pairs | mean Δ | p (Holm) |", "|---|---|---|---|"]
        for c, w in h["per_class_wilcoxon_S5_vs_S4_ndcg10"].items():
            L.append(f"| {c} | {w['n']} | {f(w['mean_diff'])} | {f(w['p_holm'], 4)} |")
    g = r.get("generation")
    if g:
        L += ["", "## End-to-end answers (8-agent workflow)", "",
              f"Runs: {g['n_runs']} (errors: {g['n_errors']}). Abstention gate threshold: **{env['abstain_confidence_threshold']}**.", "",
              f"* Answer contains every gold fact: {f(g['answer_contains_gold']['rate'])} (n={g['answer_contains_gold']['n']})",
              f"* Citation recall / precision (document level): {f(g['citation_recall']['mean'])} / {f(g['citation_precision']['mean'])}",
              f"* Claims supported rate: {f(g['claims_supported_rate']['mean'])}",
              f"* Correct abstention on unanswerable questions: {f(g['abstention_on_unanswerable']['rate'])} (n={g['abstention_on_unanswerable']['n']})",
              f"* False abstention on answerable questions: {f(g['false_abstention_on_answerable']['rate'])} (n={g['false_abstention_on_answerable']['n']})", "",
              "| class | answer contains gold | n |", "|---|---|---|"]
        for c, v in g["by_class"].items():
            L.append(f"| {c} | {f(v['answer_contains_gold'])} | {v['n']} |")
        L += ["", "Answer-contains-gold is a lexical check; the mock LLM is extractive, so multi-hop questions (which need composing two documents) "
                  "score 0 by construction of the mock, not because of the retrieval. A real LLM must be evaluated before drawing conclusions."]
    cl = r.get("classifier")
    if cl:
        L += ["", "## Query classifier (rule-based) vs benchmark labels", "", f"Accuracy {f(cl['accuracy'])}; per-class recall: " +
              ", ".join(f"{k} {f(v)}" for k, v in cl["per_class_recall"].items()) + ". The rules were **not** tuned on the benchmark."]
    if cal:
        L += ["", "## Abstention-gate calibration (`calibration.json`)", "",
              f"Chosen threshold **{cal['chosen_threshold']}** on dev (n={cal['dev']['n_answerable']}+{cal['dev']['n_unanswerable']} unanswerable); "
              f"test: answerable kept {f(cal['test']['answerable_kept'])}, unanswerable abstained {f(cal['test']['unanswerable_abstained'])} "
              f"(n={cal['test']['n_unanswerable']} unanswerable) vs {f(cal['test_without_gate']['unanswerable_abstained'])} without the gate. "
              f"AUROC dev {f(cal['auroc_dev'])}, test {f(cal['auroc_test'])}. {cal['caveat']}"]
    L += ["", "## Caveats", ""] + [f"* {n}" for n in r["notes"]]
    out = ROOT.parent / "docs" / "research" / "results.md"
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
